"""Write eval/employers.md: normalizer and resolver scores on the golden set, resolution
stats, and the 20 largest resolved employers with every name variant seen.

Run after `uv run filed resolve`.
"""

from __future__ import annotations

import csv
import re
from pathlib import Path

import duckdb

from etl.names import normalize_name

ROOT = Path(__file__).resolve().parent.parent
GOLDEN = ROOT / "tests" / "golden_employers.csv"
OUT = ROOT / "eval" / "employers.md"


def score(pairs, predict):
    tp = fp = fn = tn = 0
    wrong = []
    for p in pairs:
        pred, actual = predict(p), p["same"] == "1"
        tp += pred and actual
        fp += pred and not actual
        fn += actual and not pred
        tn += not pred and not actual
        if pred != actual:
            wrong.append(p)
    return tp, fp, fn, tn, wrong


def fmt_scores(label, tp, fp, fn, tn):
    p = tp / (tp + fp) if tp + fp else float("nan")
    r = tp / (tp + fn) if tp + fn else float("nan")
    return f"| {label} | {tp} | {fp} | {fn} | {tn} | {p:.1%} | {r:.1%} |"


def main() -> None:
    con = duckdb.connect(str(ROOT / "data" / "work" / "filed.duckdb"), read_only=True)
    pairs = list(csv.DictReader(GOLDEN.open()))

    def employer_of(name: str):
        # The employer holding most of the rows filed under this exact spelling.
        clean = re.sub(r"\s+", " ", name).strip()
        row = con.execute(
            "SELECT employer_id FROM lca WHERE employer_name = ? "
            "GROUP BY 1 ORDER BY count(*) DESC LIMIT 1",
            [clean],
        ).fetchone()
        if row:
            return row[0]
        # A spelling never filed (the brief's "Google, L.L.C."): route it as the resolver
        # routes a row with no FEIN, to the employer holding most rows with its normalized name.
        row = con.execute(
            "SELECT l.employer_id FROM lca l JOIN name_norm n ON n.raw = l.employer_name "
            "WHERE n.norm = ? GROUP BY 1 ORDER BY count(*) DESC LIMIT 1",
            [normalize_name(name)],
        ).fetchone()
        return row[0] if row else ("unmatched", name)

    def by_resolver(p):
        return employer_of(p["name_a"]) == employer_of(p["name_b"])

    def by_normalizer(p):
        return normalize_name(p["name_a"]) == normalize_name(p["name_b"])

    n_tp, n_fp, n_fn, n_tn, n_wrong = score(pairs, by_normalizer)
    r_tp, r_fp, r_fn, r_tn, r_wrong = score(pairs, by_resolver)

    q = lambda sql: con.execute(sql).fetchall()  # noqa: E731
    methods = q("SELECT match_method, count(*) FROM lca GROUP BY 1 ORDER BY 2 DESC")
    fy23 = q(
        "SELECT match_method, count(*) FROM lca WHERE fiscal_year = 2023 GROUP BY 1 ORDER BY 2 DESC"
    )
    totals = q("""
        SELECT (SELECT count(*) FROM employers),
               (SELECT count(*) FROM employers WHERE fein IS NOT NULL),
               (SELECT count(*) FROM employers WHERE fein IS NULL),
               (SELECT count(*) FROM employer_aliases),
               (SELECT count(*) FROM possible_links),
               (SELECT count(*) FROM lca)
    """)[0]
    top = q("""
        SELECT employer_id, display_name, fein, state, lca_rows FROM employers
        ORDER BY lca_rows DESC LIMIT 20
    """)

    lines = [
        "# Employer resolution",
        "",
        "Generated by `uv run python scripts/eval_employers.py`.",
        "",
        "## Golden set",
        "",
        f"{len(pairs)} hand-labeled pairs of real employer spellings from the LCA files "
        f"(`tests/golden_employers.csv`): {sum(p['same'] == '1' for p in pairs)} pairs of the same "
        f"employer and {sum(p['same'] == '0' for p in pairs)} pairs of different employers. Each "
        "label is backed by the FEINs the two spellings were filed under.",
        "",
        "A positive is a prediction that the two names are the same employer.",
        "",
        "| Method | TP | FP | FN | TN | Precision | Recall |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
        fmt_scores("Normalized name equal", n_tp, n_fp, n_fn, n_tn),
        fmt_scores("Full resolver (FEIN first)", r_tp, r_fp, r_fn, r_tn),
        "",
        "The normalizer alone merges legal entities that differ only in legal form (for",
        "example ASML US, LP and ASML US, LLC, which have different FEINs). Grouping by FEIN",
        "first keeps them apart, and the FEIN also joins spellings no name rule can, such as",
        "IBM Corporation and International Business Machines Corporation.",
        "",
        "Normalizer errors:",
        "",
    ]
    for p in n_wrong:
        kind = "missed" if p["same"] == "1" else "false merge"
        lines.append(
            f"- {kind}: `{p['name_a']}` / `{p['name_b']}` "
            f"(`{normalize_name(p['name_a'])}` vs `{normalize_name(p['name_b'])}`)"
        )
    lines += ["", "Resolver errors:", ""]
    lines += [
        f"- {'missed' if p['same'] == '1' else 'false merge'}: `{p['name_a']}` / `{p['name_b']}`"
        for p in r_wrong
    ] or ["- none"]
    lines += [
        "",
        "## Resolution",
        "",
        f"- Cases: {totals[5]:,}",
        f"- Employers: {totals[0]:,} ({totals[1]:,} by FEIN, {totals[2]:,} by name and state)",
        f"- Distinct spellings kept as aliases: {totals[3]:,}",
        f"- Possible links (different FEINs, same normalized name, not merged): {totals[4]:,}",
        "",
        "Cases by how their employer was found:",
        "",
        "| Method | All years | FY2023 |",
        "| --- | ---: | ---: |",
    ]
    fy23d = dict(fy23)
    for m, n in methods:
        lines.append(f"| {m} | {n:,} | {fy23d.get(m, 0):,} |")
    lines += [
        "",
        "FY2023 files carry no FEIN, so FY2023 cases are matched to a FEIN employer by",
        "normalized name and employer state (see docs/decisions.md D11).",
        "",
        "## 20 largest employers and their name variants",
        "",
    ]
    for eid, name, fein, state, n in top:
        variants = q(
            f"SELECT name, rows FROM employer_aliases WHERE employer_id = {eid} ORDER BY rows DESC"
        )
        years = q(
            f"SELECT fiscal_year, count(*) FROM lca WHERE employer_id = {eid} GROUP BY 1 ORDER BY 1"
        )
        ys = ", ".join(f"FY{y}: {c:,}" for y, c in years)
        lines.append(f"**{name}** (FEIN {fein or 'none'}, {state}), {n:,} cases ({ys})")
        lines.append("")
        lines += [f"- {v} ({c:,})" for v, c in variants]
        lines.append("")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"normalizer P={n_tp / (n_tp + n_fp):.3f} R={n_tp / (n_tp + n_fn):.3f}")
    print(f"resolver   P={r_tp / max(r_tp + r_fp, 1):.3f} R={r_tp / (r_tp + r_fn):.3f}")


if __name__ == "__main__":
    main()
